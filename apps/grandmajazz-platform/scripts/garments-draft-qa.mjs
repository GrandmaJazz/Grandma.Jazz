import { chromium } from "/root/hermes-agent/node_modules/playwright/index.mjs";
import { mkdir, writeFile } from "node:fs/promises";
import assert from "node:assert/strict";
import sharp from "sharp";

const base = "http://127.0.0.1:3024";
const out = "/tmp/grandmajazz-draft-qa";
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ executablePath: "/root/.cache/ms-playwright/chromium_headless_shell-1217/chrome-headless-shell-linux64/chrome-headless-shell", args: ["--no-sandbox"] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, recordVideo: { dir: out } });
const errors = []; page.on("pageerror", e => errors.push(e.message));
const svgFile = number => ({ name: `Page ${number}.svg`, mimeType: "image/svg+xml", buffer: Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="400" height="600"><rect width="400" height="600" fill="${number % 2 ? "#dcefe6" : "#e3d3df"}"/><text x="20" y="80" font-size="24">UNPUBLISHED QA</text><text x="100" y="330" font-size="120">${number}</text></svg>`) });
const manifest = async () => (await (await fetch(`${base}/api/garments/issues`)).json()).issues;
try {
  const before = await manifest();
  await page.goto(`${base}/garments/manage`);
  await page.getByLabel("Admin key", { exact: true }).fill("local-browser-qa-only");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await page.getByLabel("Issue title", { exact: true }).fill("Twenty SVG pages - isolated QA");
  await page.getByLabel("Choose magazine files").setInputFiles(Array.from({ length: 19 }, (_, i) => svgFile(19 - i)));
  await page.getByText("Pages ready", { exact: true }).waitFor({ timeout: 120000 });
  assert.equal(await page.locator(".garments-upload-pages li").count(), 19);
  const titles = await page.locator(".garments-upload-pages li > div > p").allTextContents();
  assert(titles[1].startsWith("Page 2.svg")); assert(titles[9].startsWith("Page 10.svg"));
  const choosing = page.waitForEvent("filechooser");
  await page.getByRole("button", { name: "Add page", exact: true }).click();
  await (await choosing).setFiles(svgFile(20));
  await page.waitForFunction(() => document.querySelectorAll(".garments-upload-pages li").length === 20);
  await page.getByText("Pages ready", { exact: true }).waitFor();
  await page.getByLabel("Blank back cover").uncheck();
  await page.getByRole("button", { name: "Preview magazine", exact: true }).click();
  await page.waitForFunction(() => document.querySelector("dialog [data-mode]")?.dataset.mode === "reading", null, { timeout: 60000 });
  assert.deepEqual(await manifest(), before);
  const pixels = await sharp(await page.locator("dialog canvas").screenshot()).stats();
  assert(pixels.channels[0].stdev > 20);
  await page.getByRole("button", { name: "Next preview page", exact: true }).click();
  await page.waitForFunction(() => document.querySelector("dialog [data-mode]")?.dataset.mode === "reading");
  assert.equal(await page.locator("dialog [data-mode]").getAttribute("data-page"), "3");
  await page.screenshot({ path: `${out}/desktop-3d-preview.png` });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(500);
  assert(await page.locator("dialog").evaluate(el => el.scrollWidth <= el.clientWidth));
  await page.screenshot({ path: `${out}/mobile-3d-preview.png` });
  await page.getByRole("button", { name: "Page image preview", exact: true }).click();
  assert.equal(await page.locator("dialog figure").count(), 20);
  await page.getByRole("button", { name: "Close preview", exact: true }).click();
  assert(await page.getByRole("button", { name: "Preview magazine", exact: true }).evaluate(el => document.activeElement === el));
  assert.equal(await page.locator(".garments-upload-pages li").count(), 20);
  assert.deepEqual(await manifest(), before);
  await page.getByRole("button", { name: "Save and publish", exact: true }).click();
  await page.waitForURL(/\/garments\/twenty-svg-pages/);
  await page.waitForFunction(() => document.querySelector("[data-mode]")?.dataset.mode === "reading", null, { timeout: 60000 });
  const after = await manifest(); assert.equal(after.length, before.length + 1);
  const issue = after.at(-1); assert.equal(issue.pages.length, 18); assert(issue.backCover.title.startsWith("Page 20.svg"));
  assert.deepEqual(errors, []);
  await writeFile(`${out}/result.json`, JSON.stringify({ twentySeparateSVGs: true, batchOrder: true, addPage: true, unpublished3DPreview: true, mobilePreview: true, all20FacesInFallback: true, explicitPublication: true, errors }, null, 2));
  console.log("20 SVG pages: batch ordering, Add page, unpublished 3D/mobile preview, save and publish: PASS");
} finally { await page.context().close(); await browser.close(); }
